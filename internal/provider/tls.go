// With a user-supplied HTTP certificate the operator cannot sign the admin
// client certificate its securityconfig Job authenticates with: it needs the
// key of the CA the nodes trust on HTTP. The provider therefore keeps a small
// CA of its own for that certificate, and has the nodes trust both the
// user's CA and that one.
const (
	caKey  = "ca.crt"
	caKKey = "ca.key"

	// adminCertValidity and adminCertRenewBefore bound the provider-issued
	// admin certificate; adminCAValidity outlives many of them.
	adminCAValidity      = 10 * 365 * 24 * time.Hour
	adminCertValidity    = 2 * 365 * 24 * time.Hour
	adminCertRenewBefore = 30 * 24 * time.Hour
)

var (
	tlsPath = field.NewPath("spec", "parameters", "tls")

	issuerKinds = []definition.IssuerKind{definition.IssuerKindIssuer, definition.IssuerKindClusterIssuer}

	certificateSecretKeys = []string{corev1.TLSCertKey, corev1.TLSPrivateKeyKey, caKey}

	certificateGVK = schema.GroupVersionKind{Group: "cert-manager.io", Version: "v1", Kind: "Certificate"}
)

// issuedCertificateName names the cert-manager Certificate, and the Secret it
// writes, that holds the HTTP certificate signed by the user's issuer.
func issuedCertificateName(clusterName string) string { return clusterName + "-tls-http" }

// trustedCAName names the Secret with the CAs the nodes trust on HTTP.
func trustedCAName(clusterName string) string { return clusterName + "-tls-http-ca" }

// adminCAName names the provider's CA for the admin client certificate.
func adminCAName(clusterName string) string { return clusterName + "-tls-admin-ca" }

// adminCertName names the admin client certificate's Secret.
func adminCertName(clusterName string) string { return clusterName + "-tls-admin" }

// adminDN is the subject of the provider-issued admin certificate, as the
// security plugin's admin_dn setting spells it.
func adminDN(clusterName string) string { return "CN=admin,OU=" + clusterName }

// instanceTLSParameters returns the TLS parameters of in, with defaults
// applied and an issuer without a name dropped.
func instanceTLSParameters(in *corev1alpha1.Instance) (definition.TLSParameters, error) {
	params := definition.Parameters{}
	if raw := in.Spec.Parameters; raw != nil && len(raw.Raw) > 0 {
		if err := json.Unmarshal(raw.Raw, &params); err != nil {
			return definition.TLSParameters{}, fmt.Errorf("decode parameters: %w", err)
		}
	}
	tlsParams := definition.TLSParameters{}
	if params.TLS != nil {
		tlsParams = *params.TLS
	}
	if tlsParams.Issuer != nil && tlsParams.Issuer.Name == "" {
		tlsParams.Issuer = nil
	}
	if tlsParams.Issuer != nil && tlsParams.Issuer.Kind == "" {
		tlsParams.Issuer.Kind = definition.IssuerKindIssuer
	}
	return tlsParams, nil
}

// customCertificate reports whether the HTTP certificate is not generated by
// the operator.
func customCertificate(t definition.TLSParameters) bool {
	return t.CertificateSecretName != "" || t.Issuer != nil
}

// httpCertificateSecretName is the Secret with the HTTP certificate when it
// is not generated by the operator.
func httpCertificateSecretName(clusterName string, t definition.TLSParameters) string {
	if t.CertificateSecretName != "" {
		return t.CertificateSecretName
	}
	return issuedCertificateName(clusterName)
}

// certificateSource identifies where the HTTP certificate comes from; it
// can't change on a running cluster, whose nodes and clients trust that CA.
func certificateSource(t definition.TLSParameters) string {
	switch {
	case t.CertificateSecretName != "":
		return "secret " + strconv.Quote(t.CertificateSecretName)
	case t.Issuer != nil:
		return fmt.Sprintf("%s %q", t.Issuer.Kind, t.Issuer.Name)
	default:
		return "generated"
	}
}

// clientHost is the host clients connect to, so the name the HTTP
// certificate must cover: the dedicated topology's client Service, else the
// operator's cluster Service.
func clientHost(clusterName, namespace, topology string) string {
	if topology == common.TopologyDedicated {
		return clientServiceHost(clusterName, namespace)
	}
	return clusterName + "." + namespace + ".svc"
}

// validateTLS checks the TLS parameters of an Instance alone.
func validateTLS(in, old *corev1alpha1.Instance) field.ErrorList {
	t, err := instanceTLSParameters(in)
	if err != nil {
		return field.ErrorList{field.Invalid(field.NewPath("spec", "parameters"), "", err.Error())}
	}
	var errs field.ErrorList
	if t.Issuer != nil && !slices.Contains(issuerKinds, t.Issuer.Kind) {
		errs = append(errs, field.NotSupported(tlsPath.Child("issuer", "kind"), t.Issuer.Kind, issuerKinds))
	}
	if t.CertificateSecretName != "" && t.Issuer != nil {
		errs = append(errs, field.Forbidden(tlsPath.Child("issuer"), "use either a certificate secret or an issuer, not both"))
	}
	if old != nil {
		if before, err := instanceTLSParameters(old); err == nil && certificateSource(before) != certificateSource(t) {
			errs = append(errs, field.Forbidden(tlsPath,
				fmt.Sprintf("the certificate source cannot be changed after creation; keep %s", certificateSource(before))))
		}
	}
	return errs
}

// validateTLSReferences checks the user's certificate Secret or issuer.
func validateTLSReferences(c *controller.Context) (field.ErrorList, error) {
	t, err := instanceTLSParameters(c.Instance())
	if err != nil {
		return nil, err
	}
	switch {
	case t.CertificateSecretName != "":
		path := tlsPath.Child("certificateSecretName")
		secret := &corev1.Secret{}
		if err := c.Get(secret, t.CertificateSecretName); err != nil {
			if apierrors.IsNotFound(err) {
				return field.ErrorList{field.NotFound(path, t.CertificateSecretName)}, nil
			}
			return nil, fmt.Errorf("get certificate secret %q: %w", t.CertificateSecretName, err)
		}
		host := clientHost(c.Name(), c.Namespace(), topologyOf(c.Instance()))
		if err := checkCertificateSecret(secret, host); err != nil {
			return field.ErrorList{field.Invalid(path, t.CertificateSecretName, err.Error())}, nil
		}
	case t.Issuer != nil:
		issuer := &unstructured.Unstructured{}
		issuer.SetGroupVersionKind(certificateGVK.GroupVersion().WithKind(string(t.Issuer.Kind)))
		key := client.ObjectKey{Name: t.Issuer.Name}
		if t.Issuer.Kind == definition.IssuerKindIssuer {
			key.Namespace = c.Namespace()
		}
		path := tlsPath.Child("issuer")
		if err := c.Client().Get(c.Context(), key, issuer); err != nil {
			switch {
			case meta.IsNoMatchError(err):
				return field.ErrorList{field.Invalid(path, t.Issuer.Name, "cert-manager is not installed")}, nil
			case apierrors.IsNotFound(err):
				return field.ErrorList{field.NotFound(path.Child("name"), t.Issuer.Name)}, nil
			}
			return nil, fmt.Errorf("get %s %q: %w", t.Issuer.Kind, t.Issuer.Name, err)
		}
	}
	return nil, nil
}

// checkCertificateSecret checks that a Secret holds a PKCS#8 key and a
// certificate for host, issued by its ca.crt.
func checkCertificateSecret(secret *corev1.Secret, host string) error {
	var missing []string
	for _, key := range certificateSecretKeys {
		if len(secret.Data[key]) == 0 {
			missing = append(missing, strconv.Quote(key))
		}
	}
	if len(missing) > 0 {
		return fmt.Errorf("missing %s", strings.Join(missing, ", "))
	}
	if block, _ := pem.Decode(secret.Data[corev1.TLSPrivateKeyKey]); block == nil || block.Type != "PRIVATE KEY" {
		return errors.New("tls.key must be a PEM-encoded PKCS#8 key (BEGIN PRIVATE KEY), which OpenSearch requires")
	}
	pair, err := tls.X509KeyPair(secret.Data[corev1.TLSCertKey], secret.Data[corev1.TLSPrivateKeyKey])
	if err != nil {
		return fmt.Errorf("tls.crt and tls.key: %w", err)
	}
	leaf, err := x509.ParseCertificate(pair.Certificate[0])
	if err != nil {
		return fmt.Errorf("tls.crt: %w", err)
	}
	roots := x509.NewCertPool()
	if !roots.AppendCertsFromPEM(secret.Data[caKey]) {
		return errors.New("ca.crt holds no PEM certificate")
	}
	intermediates := x509.NewCertPool()
	for _, der := range pair.Certificate[1:] {
		if cert, err := x509.ParseCertificate(der); err == nil {
			intermediates.AddCert(cert)
		}
	}
	if _, err := leaf.Verify(x509.VerifyOptions{
		DNSName:       host,
		Roots:         roots,
		Intermediates: intermediates,
		KeyUsages:     []x509.ExtKeyUsage{x509.ExtKeyUsageServerAuth},
	}); err != nil {
		return fmt.Errorf("tls.crt is not valid for %s with ca.crt: %w", host, err)
	}
	return nil
}

// syncHTTPCertificate prepares the Secrets a user-supplied HTTP certificate
// needs and returns the OpenSearchCluster security settings that use them,
// or nil when the operator generates the certificate. It waits while the
// issuer has not signed the certificate yet.
func syncHTTPCertificate(c *controller.Context, t definition.TLSParameters, topology string) (*opensearchv1.Security, error) {
	if !customCertificate(t) {
		return nil, nil
	}
	if t.Issuer != nil {
		if err := applyIssuedCertificate(c, t.Issuer, topology); err != nil {
			return nil, err
		}
	}

	certName := httpCertificateSecretName(c.Name(), t)
	cert := &corev1.Secret{}
	if err := c.Get(cert, certName); err != nil {
		if apierrors.IsNotFound(err) {
			return nil, controller.WaitFor(fmt.Sprintf("waiting for certificate secret %q", certName))
		}
		return nil, fmt.Errorf("get certificate secret %q: %w", certName, err)
	}
	userCA := cert.Data[caKey]
	if len(userCA) == 0 || len(cert.Data[corev1.TLSCertKey]) == 0 {
		return nil, controller.WaitFor(fmt.Sprintf("waiting for certificate secret %q to hold tls.crt and ca.crt", certName))
	}

	adminCACert, adminCAKey, err := ensureAdminCA(c)
	if err != nil {
		return nil, err
	}
	if err := ensureAdminCert(c, adminCACert, adminCAKey, userCA); err != nil {
		return nil, err
	}

	trusted := &corev1.Secret{
		ObjectMeta: c.ObjectMeta(trustedCAName(c.Name())),
		Data:       map[string][]byte{caKey: joinPEM(userCA, adminCACert)},
	}
	if err := c.Apply(trusted); err != nil {
		return nil, fmt.Errorf("apply trusted CA secret: %w", err)
	}

	return &opensearchv1.Security{
		Tls: &opensearchv1.TlsConfig{
			Http: &opensearchv1.TlsConfigHttp{
				TlsCertificateConfig: opensearchv1.TlsCertificateConfig{
					Secret:   corev1.LocalObjectReference{Name: certName},
					CaSecret: corev1.LocalObjectReference{Name: trustedCAName(c.Name())},
				},
				AdminDn: []string{adminDN(c.Name())},
			},
		},
		Config: &opensearchv1.SecurityConfig{
			AdminSecret: corev1.LocalObjectReference{Name: adminCertName(c.Name())},
		},
	}, nil
}

// applyIssuedCertificate asks cert-manager for the HTTP certificate.
// OpenSearch only reads PKCS#8 keys, which cert-manager does not write by
// default.
func applyIssuedCertificate(c *controller.Context, issuer *definition.IssuerReference, topology string) error {
	cert := &unstructured.Unstructured{}
	cert.SetGroupVersionKind(certificateGVK)
	om := c.ObjectMeta(issuedCertificateName(c.Name()))
	cert.SetName(om.Name)
	cert.SetNamespace(om.Namespace)
	cert.SetLabels(om.Labels)
	dnsNames := make([]any, 0, 8)
	for _, name := range certificateDNSNames(c.Name(), c.Namespace(), topology) {
		dnsNames = append(dnsNames, name)
	}
	cert.Object["spec"] = map[string]any{
		"secretName": issuedCertificateName(c.Name()),
		"commonName": clientHost(c.Name(), c.Namespace(), topology),
		"dnsNames":   dnsNames,
		"usages":     []any{"server auth", "digital signature", "key encipherment"},
		"privateKey": map[string]any{
			"algorithm":      "RSA",
			"size":           int64(2048),
			"encoding":       "PKCS8",
			"rotationPolicy": "Always",
		},
		"issuerRef": map[string]any{
			"group": "cert-manager.io",
			"kind":  string(issuer.Kind),
			"name":  issuer.Name,
		},
	}
	if err := c.Apply(cert); err != nil {
		if meta.IsNoMatchError(err) {
			return errors.New("cert-manager is not installed: the Certificate kind is unknown")
		}
		return fmt.Errorf("apply certificate: %w", err)
	}
	return nil
}

// certificateDNSNames are the names an issued HTTP certificate covers: the
// cluster Service and, in the dedicated topology, the client Service, in
// every form a client in the cluster may use.
func certificateDNSNames(clusterName, namespace, topology string) []string {
	services := []string{clusterName}
	if topology == common.TopologyDedicated {
		services = []string{clientServiceName(clusterName), clusterName}
	}
	var names []string
	for _, svc := range services {
		names = append(names,
			svc+"."+namespace+".svc",
			svc+"."+namespace+".svc.cluster.local",
			svc+"."+namespace,
			svc,
		)
	}
	return names
}

// ensureAdminCA returns the provider's admin CA, creating it once.
func ensureAdminCA(c *controller.Context) (certPEM, keyPEM []byte, err error) {
	secret := &corev1.Secret{}
	err = c.Get(secret, adminCAName(c.Name()))
	if err == nil && len(secret.Data[caKey]) > 0 && len(secret.Data[caKKey]) > 0 {
		return secret.Data[caKey], secret.Data[caKKey], nil
	}
	if err != nil && !apierrors.IsNotFound(err) {
		return nil, nil, fmt.Errorf("get admin CA secret: %w", err)
	}
	certPEM, keyPEM, err = newAdminCA(c.Name(), time.Now())
	if err != nil {
		return nil, nil, err
	}
	ca := &corev1.Secret{
		ObjectMeta: c.ObjectMeta(adminCAName(c.Name())),
		Data:       map[string][]byte{caKey: certPEM, caKKey: keyPEM},
	}
	if err := c.Apply(ca); err != nil {
		return nil, nil, fmt.Errorf("apply admin CA secret: %w", err)
	}
	return certPEM, keyPEM, nil
}

// ensureAdminCert keeps the admin client certificate signed by the admin CA
// and valid for a while, with the user's CA to verify the nodes with.
func ensureAdminCert(c *controller.Context, caCertPEM, caKeyPEM, userCA []byte) error {
	secret := &corev1.Secret{}
	if err := c.Get(secret, adminCertName(c.Name())); err != nil && !apierrors.IsNotFound(err) {
		return fmt.Errorf("get admin certificate secret: %w", err)
	}
	certPEM, keyPEM := secret.Data[corev1.TLSCertKey], secret.Data[corev1.TLSPrivateKeyKey]
	if !adminCertValid(certPEM, caCertPEM, time.Now()) {
		var err error
		certPEM, keyPEM, err = newAdminCert(c.Name(), caCertPEM, caKeyPEM, time.Now())
		if err != nil {
			return err
		}
	} else if bytes.Equal(secret.Data[caKey], userCA) {
		return nil
	}
	admin := &corev1.Secret{
		ObjectMeta: c.ObjectMeta(adminCertName(c.Name())),
		Type:       corev1.SecretTypeTLS,
		Data: map[string][]byte{
			corev1.TLSCertKey:       certPEM,
			corev1.TLSPrivateKeyKey: keyPEM,
			caKey:                   userCA,
		},
	}
	if err := c.Apply(admin); err != nil {
		return fmt.Errorf("apply admin certificate secret: %w", err)
	}
	return nil
}

// adminCertValid reports whether certPEM is signed by the CA and not about
// to expire.
func adminCertValid(certPEM, caCertPEM []byte, now time.Time) bool {
	cert, err := parseCertificatePEM(certPEM)
	if err != nil {
		return false
	}
	ca, err := parseCertificatePEM(caCertPEM)
	if err != nil {
		return false
	}
	return cert.CheckSignatureFrom(ca) == nil && now.Add(adminCertRenewBefore).Before(cert.NotAfter)
}

func newAdminCA(clusterName string, now time.Time) (certPEM, keyPEM []byte, err error) {
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return nil, nil, fmt.Errorf("generate admin CA key: %w", err)
	}
	template := &x509.Certificate{
		SerialNumber:          randomSerial(),
		Subject:               pkix.Name{CommonName: "admin-ca", OrganizationalUnit: []string{clusterName}},
		NotBefore:             now.Add(-time.Hour),
		NotAfter:              now.Add(adminCAValidity),
		KeyUsage:              x509.KeyUsageCertSign | x509.KeyUsageCRLSign,
		BasicConstraintsValid: true,
		IsCA:                  true,
	}
	der, err := x509.CreateCertificate(rand.Reader, template, template, &key.PublicKey, key)
	if err != nil {
		return nil, nil, fmt.Errorf("create admin CA: %w", err)
	}
	keyPEM, err = pkcs8PEM(key)
	if err != nil {
		return nil, nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), keyPEM, nil
}

func newAdminCert(clusterName string, caCertPEM, caKeyPEM []byte, now time.Time) (certPEM, keyPEM []byte, err error) {
	ca, err := parseCertificatePEM(caCertPEM)
	if err != nil {
		return nil, nil, fmt.Errorf("admin CA: %w", err)
	}
	block, _ := pem.Decode(caKeyPEM)
	if block == nil {
		return nil, nil, errors.New("admin CA key: no PEM block")
	}
	caKey, err := x509.ParsePKCS8PrivateKey(block.Bytes)
	if err != nil {
		return nil, nil, fmt.Errorf("admin CA key: %w", err)
	}
	key, err := rsa.GenerateKey(rand.Reader, 2048)
	if err != nil {
		return nil, nil, fmt.Errorf("generate admin key: %w", err)
	}
	template := &x509.Certificate{
		SerialNumber: randomSerial(),
		Subject:      pkix.Name{CommonName: "admin", OrganizationalUnit: []string{clusterName}},
		NotBefore:    now.Add(-time.Hour),
		NotAfter:     now.Add(adminCertValidity),
		KeyUsage:     x509.KeyUsageDigitalSignature | x509.KeyUsageKeyEncipherment,
		ExtKeyUsage:  []x509.ExtKeyUsage{x509.ExtKeyUsageClientAuth},
	}
	der, err := x509.CreateCertificate(rand.Reader, template, ca, &key.PublicKey, caKey)
	if err != nil {
		return nil, nil, fmt.Errorf("create admin certificate: %w", err)
	}
	keyPEM, err = pkcs8PEM(key)
	if err != nil {
		return nil, nil, err
	}
	return pem.EncodeToMemory(&pem.Block{Type: "CERTIFICATE", Bytes: der}), keyPEM, nil
}

func pkcs8PEM(key *rsa.PrivateKey) ([]byte, error) {
	der, err := x509.MarshalPKCS8PrivateKey(key)
	if err != nil {
		return nil, fmt.Errorf("encode key: %w", err)
	}
	return pem.EncodeToMemory(&pem.Block{Type: "PRIVATE KEY", Bytes: der}), nil
}

func parseCertificatePEM(data []byte) (*x509.Certificate, error) {
	block, _ := pem.Decode(data)
	if block == nil || block.Type != "CERTIFICATE" {
		return nil, errors.New("no PEM certificate")
	}
	return x509.ParseCertificate(block.Bytes)
}

func randomSerial() *big.Int {
	serial, err := rand.Int(rand.Reader, new(big.Int).Lsh(big.NewInt(1), 127))
	if err != nil {
		return big.NewInt(time.Now().UnixNano())
	}
	return serial
}

// joinPEM concatenates PEM bundles, each ending in a newline.
func joinPEM(bundles ...[]byte) []byte {
	var out []byte
	for _, b := range bundles {
		out = append(out, bytes.TrimSpace(b)...)
		out = append(out, '\n')
	}
	return out
}

// clientCA returns the CA clients verify the HTTP certificate with: the
// user's CA, or the one the operator generated.
func clientCA(c *controller.Context) ([]byte, error) {
	t, err := instanceTLSParameters(c.Instance())
	if err != nil {
		return nil, err
	}
	name := caSecretName(c.Name())
	if customCertificate(t) {
		name = httpCertificateSecretName(c.Name(), t)
	}
	secret := &corev1.Secret{}
	if err := c.Get(secret, name); err != nil {
		return nil, fmt.Errorf("get CA secret %q: %w", name, err)
	}
	if len(secret.Data[caKey]) == 0 {
		return nil, fmt.Errorf("CA secret %q has no %s", name, caKey)
	}
	return secret.Data[caKey], nil
}

// validateSecurityMatches repeats the creation-only rules for the HTTP
// certificate and spec.userSecretRef against the running cluster.
func validateSecurityMatches(existing *opensearchv1.OpenSearchCluster, in *corev1alpha1.Instance) (field.ErrorList, error) {
	t, err := instanceTLSParameters(in)
	if err != nil {
		return nil, err
	}
	var httpSecret, credentials string
	if sec := existing.Spec.Security; sec != nil {
		if sec.Tls != nil && sec.Tls.Http != nil && !sec.Tls.Http.Generate {
			httpSecret = sec.Tls.Http.Secret.Name
		}
		if sec.Config != nil {
			credentials = sec.Config.AdminCredentialsSecret.Name
		}
	}
	var errs field.ErrorList
	want := ""
	if customCertificate(t) {
		want = httpCertificateSecretName(in.Name, t)
	}
	if want != httpSecret {
		current := "generated"
		if httpSecret != "" {
			current = "secret " + strconv.Quote(httpSecret)
		}
		errs = append(errs, field.Forbidden(tlsPath,
			fmt.Sprintf("the certificate source cannot be changed after creation; the cluster uses a %s certificate", current)))
	}
	if in.Spec.UserSecretRef != nil && credentials != adminCredentialsName(in.Name) {
		errs = append(errs, field.Forbidden(userSecretRefPath, "can only be set when the instance is created"))
	}
	return errs, nil
}
